// ── 자동차세 (지방세법 제127조 — 비영업용 승용, cc당 세율 + 지방교육세 30%) ──
// 차령 3년차부터 5%씩 경감, 최대 50% (제127조 산식). 전기·수소차는 정액 10만원+교육세.
export function carTaxAnnual(cc: number, carAge: number): number {
  const perCc = cc <= 1000 ? 80 : cc <= 1600 ? 140 : 200;
  const base = cc * perCc;
  const discount =
    carAge >= 3 ? Math.min(0.05 * (Math.min(carAge, 12) - 2), 0.5) : 0;
  const tax = base * (1 - discount);
  return Math.floor(tax * 1.3); // 지방교육세 30% 포함
}

