const won = (n: number) => `${Math.round(n).toLocaleString("ko-KR")}원`;

function salaryNetMonthly(annual: number): number {
  // 1인 가구, 비과세 월 20만원 기준
  return calcMonthlyDeductions(annual / 12, 200_000, 1, 0).net;
}

function severanceEstimate(monthlyPay: number, years: number): number {
  // 3개월 평균 91.25일 기준 약식 — 1일 평균임금 × 30 × 근속연수
  return ((monthlyPay * 3) / 91.25) * 30 * years;
}

function loanEqualTotalMonthly(P: number, annualRate: number, years: number) {
  const r = annualRate / 100 / 12;
  const n = years * 12;
  const M = (P * r * Math.pow(1 + r, n)) / (Math.pow(1 + r, n) - 1);
  return { monthly: M, totalInterest: M * n - P };
}

function airconExtraCost(hoursPerDay: number): number {
  // 1.8kW, 가동률 70%, 30일, 기본 사용량 300kWh, 하계 저압 기준
  const airconKwh = 1.8 * hoursPerDay * 30 * 0.7;
  return (
    calcResidentialBill(300 + airconKwh, 8, "low").total -
    calcResidentialBill(300, 8, "low").total
  );
}

