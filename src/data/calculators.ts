export function getCalc(id: string): CalculatorInfo {
  const calc = calculators.find((c) => c.id === id);
  if (!calc) throw new Error(`Unknown calculator: ${id}`);
  return calc;
}

// 계산기 레이아웃 공용 메타데이터 — canonical·OG 포함
export function buildCalcMetadata(id: string): Metadata {
  const calc = getCalc(id);
  const path = `/calculators/${id}`;
  return {
    title: { absolute: calc.metaTitle },
    description: calc.metaDescription,
    keywords: calc.keywords,
    alternates: { canonical: path },
    openGraph: {
      title: calc.metaTitle,
      description: calc.metaDescription,
      url: path,
      siteName: "상식왕 퀴즈",
      locale: "ko_KR",
      type: "website",
    },
  };
}
