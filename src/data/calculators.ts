// 주휴수당 포함 월급 환산 — 주 15시간 이상이면 주휴시간(주간시간/40×8, 최대 8h) 가산
// 월 환산시간은 (주시간+주휴)×365/7/12 반올림 (주 40h → 209시간, 관행과 일치)
export function minWageMonthly(hourly: number, weeklyHours: number): number {
  const holiday =
    weeklyHours >= 15 ? (Math.min(weeklyHours, 40) / 40) * 8 : 0;
  const monthlyHours = Math.round(((weeklyHours + holiday) * 365) / 7 / 12);
  return hourly * monthlyHours;
}

