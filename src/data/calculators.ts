// 적금 단리 이자 (월 납입, 연이율, 개월)
function savingsSimpleInterest(
  monthly: number,
  annualRate: number,
  months: number
): number {
  return ((monthly * annualRate) / 12) * ((months * (months + 1)) / 2);
}

