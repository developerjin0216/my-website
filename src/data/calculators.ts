const LOAN_TABLE: CalcTable = (() => {
  const P = 100_000_000;
  const rate = 4.0;
  const years = 30;
  const et = loanEqualTotalMonthly(P, rate, years);
  const n = years * 12;
  const r = rate / 100 / 12;
  const epFirst = P / n + P * r;
  const epTotal = (P * r * (n + 1)) / 2;
  const bulletMonthly = P * r;
  return {
    title: "1억원 대출 상환방식 비교 (연 4.0%, 30년)",
    headers: ["상환방식", "월 상환액", "총 이자"],
    rows: [
      ["원리금균등", won(et.monthly), won(et.totalInterest)],
      [
        "원금균등",
        `첫달 ${won(epFirst)} (매월 감소)`,
        won(epTotal),
      ],
      ["만기일시", `이자 ${won(bulletMonthly)}`, won(bulletMonthly * n)],
    ],
  };
})();

