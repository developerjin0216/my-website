export function getCalc(id: string): CalculatorInfo {
  const calc = calculators.find((c) => c.id === id);
  if (!calc) throw new Error(`Unknown calculator: ${id}`);
  return calc;
}

// "계산기 N종" 문구용. 손으로 적은 숫자가 10군데에 흩어져 있었고, 20번째
// 계산기를 추가했을 때 전부 19로 남아 본문이 실제와 어긋났습니다.
// 숫자를 쓰는 곳은 전부 여기를 가져다 씁니다.
export const CALC_COUNT = calculators.length;

// 계산기 레이아웃 공용 메타데이터 — canonical·OG 포함
// 도메인 분리 시 CALC_URL이 계산기 도메인을 가리켜 canonical이 자동 전환됩니다.
export function buildCalcMetadata(id: string): Metadata {
  const calc = getCalc(id);
  const url = `${CALC_URL}/calculators/${id}`;
  return {
    title: { absolute: calc.metaTitle },
    description: calc.metaDescription,
    keywords: calc.keywords,
    alternates: { canonical: url },
    openGraph: {
      title: calc.metaTitle,
      description: calc.metaDescription,
      url,
      siteName: CALC_SITE_NAME,
      locale: "ko_KR",
      type: "website",
      // 자식 세그먼트의 openGraph가 부모의 파일 기반 이미지를 대체하므로 명시 지정
      images: [
        {
          url: `${CALC_URL}/calculators/opengraph-image`,
          width: 1200,
          height: 630,
        },
      ],
    },
  };
}
