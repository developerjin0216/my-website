// /help 페이지의 "실제로 있었던 일" — 공공기관·언론이 공개한 실제 사례.
//
// 지어낸 경험담을 쓰지 않기 위한 장치입니다. 상황·결과의 모든 사실은 출처 원문에 있어야 하고,
// evidence 에는 그 근거가 되는 원문 구절을 그대로 옮겨 둡니다(화면에는 쓰지 않음).
// `node --experimental-strip-types scripts/check-help-cases.mjs` 가 출처를 다시 받아
//   ① evidence 가 원문에 실제로 있는지
//   ② 화면 문구(title·what·result·takeaway·when)의 숫자가 evidence 에 있는지
// 를 확인합니다. 사례를 고치면 반드시 다시 돌리세요.
//
// 원칙
// - 원문에 없는 교훈·조언을 덧붙이지 않습니다. takeaway 도 원문(기관 답변·기사)에 있는 말이어야 합니다.
// - 요율표(지연 배상률 등)는 옮기지 않습니다. 사례 당시 고시 기준이라 지금과 다를 수 있습니다.
// - 사례가 없는 주제는 비워 둡니다. 채우려고 억지로 찾은 사례를 넣지 않습니다.
// - PDF에서 뽑은 원문은 숫자 순서가 뒤섞여 나옵니다("약 만원이 600"). evidence 는 추출된 그대로 둡니다.
//
// 이 파일은 import 를 두지 않습니다 — 검증 스크립트가 Node 로 바로 읽어야 해서입니다.
// 주제 id 검증은 lib/helpCases.ts 가 빌드 때 합니다.

export interface HelpCaseSource {
  /** 기관·매체 */
  org: string;
  /** 원문 제목 또는 게시판 이름 */
  title: string;
  url: string;
  /** 원문 게시일 (YYYY-MM-DD). 게시판에 날짜가 없으면 생략 */
  published?: string;
}

export interface HelpCase {
  /** data/help.ts 의 주제 id */
  topic: string;
  title: string;
  /** 언제 일인지 — 원문에 나온 시점. 없으면 생략 */
  when?: string;
  /** 무슨 일이 있었나 */
  what: string;
  /** 어떻게 됐나 (기관 판단·처리 결과) */
  result: string;
  /** 원문에 있는 조언만 */
  takeaway?: string;
  source: HelpCaseSource;
  /** 원문 대조용 발췌. 공백·문장부호는 무시하고 비교합니다 */
  evidence: string[];
}

