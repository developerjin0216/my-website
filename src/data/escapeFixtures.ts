/** 장부에 적힌 번호의 범위 전체 (빠진 번호 포함) */
export function ledgerNumberRange(): string[] {
  const nums = LEDGER_ROWS.map((r) => Number(r[0]));
  const lo = Math.min(...nums);
  const hi = Math.max(...nums);
  return Array.from({ length: hi - lo + 1 }, (_, i) =>
    String(lo + i).padStart(4, "0")
  );
}

/** 선반에 실제로 있는 연도 (오름차순) */
export function shelfYears(): number[] {
  return [...SHELF_TOP, ...SHELF_BOTTOM].sort((a, b) => a - b);
}

/** 3월 중 장부에 줄이 없는 날 (쉬는 날 + 사라진 하루) */
export function marchMissingDays(): string[] {
  const have = new Set(MARCH.map((m) => m[0]));
  return Array.from({ length: 31 }, (_, i) => String(i + 1).padStart(2, "0"))
    .filter((d) => !have.has(d));
}
