// 웹 방탈출 1편 "현상되지 않은 필름" — quiz 서브도메인 /escape 의 단일 데이터 소스.
// 허브·플레이 화면·sitemap이 모두 이 파일을 읽습니다.
//
// ── 설계 원칙 (lib/escapeValidate.ts가 빌드 타임에 강제합니다) ──
// 1. 떡밥(Clue)은 반드시 심는 장면(plantedIn)보다 뒤에서 회수(payoffIn)된다.
// 2. 회수는 장면의 resolves 목록과 떡밥의 payoffIn이 양방향으로 일치해야 한다.
// 3. 결(마지막 장면)에서 최소 4개가 회수된다 — 결말이 비면 기승전결이 무너진다.
// 4. 퍼즐의 needs(선행 조건)는 그 퍼즐보다 앞선 장면에서 이미 공개돼 있어야 한다.
// 5. 단독 완결 퍼즐(그 화면만 보면 풀리는 것)이 40%를 넘지 않는다.
// 6. 후반 세 장면의 퍼즐은 모두 다른 방의 정보를 요구한다.
//    — 5·6번은 난이도 규칙입니다. 초판이 12개 중 7개가 단독 완결이라 너무 쉬웠고,
//      난이도 곡선이 뒤로 갈수록 낮아지는 문제가 있어 구조로 막았습니다.
//
// ── 문제를 글이 아니라 그림으로 ──
// 각 퍼즐은 art 키로 SVG 삽화를 하나씩 가집니다(components/escape/EscapeArt.tsx).
// 정답에 필요한 관찰 정보는 그림 쪽에 있고, body는 그림을 어떻게 읽어야 하는지만
// 설명합니다. 정보를 숨기지는 않습니다 — 숨기면 추측 게임이 되어 논리가 무너집니다.
//
// ── 정답 보호 ──
// 정답은 평문 대신 sha256(salt + 정규화된 정답)만 저장합니다. 소스 보기로 바로
// 읽히지 않게 하려는 것이며, 짧은 숫자 정답은 무차별 대입에 약하므로 완전한 보호는
// 아닙니다. 정답 수정 시 utils/escapeAnswer.ts의 normalizeAnswer와 같은 규칙으로
// 해시를 다시 계산해야 합니다.

export type SceneId =
  | "counter"
  | "display"
  | "storage"
  | "darkroom-door"
  | "darkroom"
  | "envelope";

export type Act = "기" | "승" | "전" | "결";

/** 퍼즐 삽화 키 — EscapeArt.tsx가 이 목록을 빠짐없이 구현해야 컴파일됩니다 */
export type ArtKey =
  | "ledger"
  | "envelope-rack"
  | "photo-wall"
  | "documents"
  | "shelf"
  | "rule-card"
  | "lock"
  | "chemicals"
  | "two-ledgers"
  | "filmstrip"
  | "signboard"
  | "envelope";

export interface Scene {
  id: SceneId;
  order: number; // 1부터 연속
  act: Act;
  title: string;
  place: string;
  intro: string[];
  outro: string[];
  /** 이 장면에서 회수되는 떡밥 id — Clue.payoffIn과 양방향 일치해야 함 */
  resolves: string[];
}

export interface Clue {
  id: string;
  label: string;
  /** 플레이어가 처음 볼 때의 겉보기 의미 */
  surface: string;
  /** 회수 시점에 드러나는 진짜 의미 */
  truth: string;
  plantedIn: SceneId;
  payoffIn: SceneId;
}

export interface Puzzle {
  id: string;
  scene: SceneId;
  order: number;
  title: string;
  prompt: string;
  /** 그림을 어떻게 읽어야 하는지 — 정답 자체를 적지 않습니다 */
  body: string[];
  art: ArtKey;
  inputLabel: string;
  placeholder: string;
  salt: string;
  answerHash: string;
  hints: [string, string, string];
  solved: string[];
  /** 선행 조건: 앞선 장면의 퍼즐 id 또는 떡밥 id */
  needs: string[];
}

