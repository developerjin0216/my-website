export function getScene(id: string): Scene | undefined {
  return scenes.find((s) => s.id === id);
}

export function getPuzzlesOf(sceneId: SceneId): Puzzle[] {
  return puzzles
    .filter((p) => p.scene === sceneId)
    .sort((a, b) => a.order - b.order);
}

export function getClue(id: string): Clue | undefined {
  return clues.find((c) => c.id === id);
}

export const TOTAL_PUZZLES = puzzles.length;

export const orderedScenes = [...scenes].sort((a, b) => a.order - b.order);
