//
// ── 구조 (lib/escapeValidate.ts가 빌드 타임에 강제합니다) ──
// 1. 떡밥은 심는 장면보다 뒤에서 회수된다.
// 2. 떡밥의 payoffIn과 장면의 resolves가 양방향으로 일치한다.
// 3. 결(마지막 장면)에서 최소 4개가 회수된다.
// 4. 퍼즐의 needs는 그 퍼즐보다 앞선 장면에서 이미 공개돼 있다.
// 5. 단독 완결 퍼즐이 40%를 넘지 않는다.
// 6. 후반 세 장면의 퍼즐은 모두 다른 방의 정보를 요구한다.
// 7. 모든 떡밥은 그 장면의 '사물(object)'을 통해 심긴다 — 서술로만 흘리지 않는다.
// 8. 장면마다 사물 3개 이상, 퍼즐마다 진입 서술(lead)이 있고, 장면당 서사 분량이
//    최소치를 넘는다.
//    — 7·8번은 품질 규칙입니다. 초판은 방마다 서술이 8줄뿐이고 퍼즐 화면에는
//      이야기가 한 줄도 없어서 "스토리 없이 퀴즈만 푸는" 느낌이 났습니다.
//      분량과 배치를 사람 기억에 맡기지 않고 구조로 막습니다.
//
// ── 정답 보호 ──
// sha256(salt + 정규화된 정답)만 저장합니다. 정답 수정 시 utils/escapeAnswer.ts의
// normalizeAnswer와 같은 규칙으로 해시를 다시 계산해야 합니다.

