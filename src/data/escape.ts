/** 방 안에서 살펴볼 수 있는 사물 */
export interface SceneObject {
  id: string;
  name: string;
  /** 살펴봤을 때 나오는 서술 */
  text: string[];
  /** 이 사물이 심는 떡밥 id (있으면) */
  clue?: string;
}

export interface Scene {
  id: SceneId;
  order: number;
  act: Act;
  title: string;
  place: string;
  intro: string[];
  /** 방 안의 사물 — 퍼즐 전에 둘러봅니다 */
  objects: SceneObject[];
  outro: string[];
  /** 장면을 나설 때 떠오르는 회상 — 주인공의 감정선 */
  memory: { title: string; text: string[] };
  /** 이 장면에서 회수되는 떡밥 id */
  resolves: string[];
}

export interface Clue {
  id: string;
  label: string;
  surface: string;
  truth: string;
  plantedIn: SceneId;
  payoffIn: SceneId;
}

export interface Puzzle {
  id: string;
  scene: SceneId;
  order: number;
  title: string;
  /** 퍼즐에 들어가기 전 서술 — 왜 지금 이걸 보고 있는가 */
  lead: string[];
  /** 무엇을 알아내야 하는지 */
  prompt: string;
  /** 그림을 어떻게 읽어야 하는지 */
  body: string[];
  art: ArtKey;
  inputLabel: string;
  placeholder: string;
  salt: string;
  answerHash: string;
  hints: [string, string, string];
  solved: string[];
  needs: string[];
}

