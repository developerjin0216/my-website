// ── 설계 원칙 (lib/escapeValidate.ts가 빌드 타임에 강제합니다) ──
// 1. 떡밥(Clue)은 반드시 심는 장면(plantedIn)보다 뒤에서 회수(payoffIn)된다.
// 2. 회수는 장면의 resolves 목록과 떡밥의 payoffIn이 양방향으로 일치해야 한다.
//    — 한쪽만 적어두고 잊는 사고를 막습니다.
// 3. 결(마지막 장면)에서 최소 4개가 회수된다 — 결말이 비면 기승전결이 무너집니다.
// 4. 퍼즐의 needs(선행 조건)는 그 퍼즐보다 앞선 장면에서 이미 공개돼 있어야 한다.
//    — "아직 안 준 정보로 풀어야 하는 퍼즐"을 원천 차단합니다.
//
// ── 정답 보호 ──
// 정답은 평문으로 두지 않고 sha256(salt + 정규화된 정답)만 저장합니다. 소스 보기로
// 바로 읽히지 않게 하려는 것이며, 짧은 숫자 정답은 무차별 대입에 약하므로 완전한
// 보호는 아닙니다. 정답 추가·수정 시 해시를 다시 계산해야 합니다(utils/escapeAnswer.ts
// 의 normalizeAnswer와 동일한 규칙 사용).

export type SceneId =
  | "counter"
  | "display"
  | "storage"
  | "darkroom-door"
  | "darkroom"
  | "envelope";

export type Act = "기" | "승" | "전" | "결";

export interface Scene {
  id: SceneId;
  order: number; // 1부터 연속
  act: Act;
  title: string;
  place: string;
  /** 입장 시 내레이션 */
  intro: string[];
  /** 그 방의 퍼즐을 모두 푼 뒤 나오는 서술 */
  outro: string[];
  /** 이 장면에서 회수되는 떡밥 id — Clue.payoffIn과 양방향 일치해야 함 */
  resolves: string[];
}

export interface Clue {
  id: string;
  label: string;
  /** 플레이어가 처음 볼 때의 겉보기 의미 */
  surface: string;
  /** 회수 시점에 드러나는 진짜 의미 */
  truth: string;
  plantedIn: SceneId;
  payoffIn: SceneId;
}

export interface Puzzle {
  id: string;
  scene: SceneId;
  order: number; // 장면 내 순서
  title: string;
  /** 무엇을 알아내야 하는지 */
  prompt: string;
  /** 관찰 가능한 정보 — 이것만으로 정답이 유일하게 결정돼야 합니다 */
  body: string[];
  inputLabel: string;
  placeholder: string;
  salt: string;
  answerHash: string;
  /** 3단계 힌트 — 뒤로 갈수록 직접적 */
  hints: [string, string, string];
  /** 정답 시 서술 */
  solved: string[];
  /** 선행 조건: 앞선 장면의 퍼즐 id 또는 떡밥 id */
  needs: string[];
}

