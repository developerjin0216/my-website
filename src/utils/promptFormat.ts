// 프롬프트 본문 줄바꿈 정리.
//
// 집필·수집된 본문 중 일부가 "반드시 포함할 것: ① ... ② ... ③ ..." 형태로 한 줄에
// 다 붙어 있어 읽기가 어렵습니다. 원문복사 시에도 같은 텍스트를 쓰므로, 화면용으로만
// 예쁘게 만드는 게 아니라 붙여넣었을 때도 읽기 좋아집니다.
//
// 뜻을 바꾸지 않는 범위에서만 손댑니다 — 항목 기호 앞에서 줄을 나누는 것뿐입니다.
// 이미 줄바꿈이 있는 본문은 그대로 둡니다(중복 개행만 정리).

// ①~⑳ 앞의 공백을 줄바꿈으로 바꿉니다.
// \s* 로 두면 공백을 먹은 뒤 같은 자리에서 0폭 매치가 한 번 더 일어나 개행이
// 두 번 들어갑니다(항목 사이에 빈 줄이 생김). 공백이 실제로 있을 때만 바꿉니다.
// 이미 줄 첫머리에 있는 기호는 앞에 공백이 없으므로 그대로 둡니다.
const CIRCLED = /[ \t]+(?=[①-⑳])/gu;

export function formatPromptBody(raw: string): string {
  return (
    raw
      .replace(/\r\n/g, "\n")
      .replace(CIRCLED, "\n")
      // 3줄 이상 연속 개행은 2줄로
      .replace(/\n{3,}/g, "\n\n")
      // 줄 끝 공백 제거
      .replace(/[ \t]+\n/g, "\n")
      .trim()
  );
}
